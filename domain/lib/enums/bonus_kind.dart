/// Бонусы-пикапы (спека § 5): шестиугольник на поле, засчитывается, когда
/// фигура проезжает через него. Что делает каждый — в движке
/// (`LineDutyGame`), длительности — в `GameTuning`.
enum BonusKind {
  /// Все фигуры стоят несколько секунд, рисовать можно.
  freeze,

  /// Подобравшая фигура прощает одно столкновение.
  shield,

  /// Очки за доставку ×2 на время.
  multiplier,

  /// Подобравшая фигура сама едет к своим воротам.
  autopilot,
}
